import java.awt.Font;
import java.awt.Shape;
import java.awt.font.FontRenderContext;
import java.awt.font.GlyphVector;
import java.awt.geom.AffineTransform;
import java.awt.geom.Path2D;
import java.awt.geom.PathIterator;
import java.awt.geom.Rectangle2D;
import java.io.File;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * Converts Daniel Hart's Dot-Matrix-Typeface TTFs into Dotboard's bitmap font format (.dmf).
 *
 * The typeface is drawn on an exact grid: each dot is a square contour one cell wide, and a cell is
 * unitsPerEm / 10 font units. So we sample each cell centre against the glyph outline, which gives a
 * pixel-perfect bitmap with no anti-aliasing. Glyphs whose contours aren't grid-aligned dots (e.g. the
 * placeholder boxes in the Tall cut) are skipped.
 *
 * Usage (JDK 17+, from the repo root):
 *   java -Djava.awt.headless=true tools/fontgen/FontGen.java
 *
 * .dmf format (UTF-8 text):
 *   # comments
 *   font <name>
 *   ascent <rows above baseline>
 *   descent <rows below baseline>
 *   glyph <hex code point> <advance in dots>
 *   <ascent+descent rows of '#' (lit) / '.' (unlit), each <advance> characters wide>
 */
public class FontGen {

    private static final String SRC = "tools/fontgen/fonts/";
    private static final String OUT = "core/src/main/resources/io/github/inputbiscuit/dotboard/core/fonts/";

    public static void main(String[] args) throws Exception {
        generate("Dot Matrix Regular.ttf", "regular");
        generate("Dot Matrix Bold.ttf", "bold");
        generate("Dot Matrix Bold Tall.ttf", "bold-tall");
    }

    private static void generate(String ttf, String name) throws Exception {
        Font base = Font.createFont(Font.TRUETYPE_FONT, new File(SRC + ttf));
        // Work at size = 10 so one grid cell is exactly one unit.
        Font font = base.deriveFont(10f);
        FontRenderContext frc = new FontRenderContext(new AffineTransform(), false, false);
        var metrics = font.getLineMetrics("Hg", frc);
        int ascent = Math.round(metrics.getAscent());
        int descent = Math.round(metrics.getDescent());

        new File(OUT).mkdirs();
        int count = 0;
        try (PrintWriter out = new PrintWriter(new File(OUT + name + ".dmf"), StandardCharsets.UTF_8)) {
            out.println("# Generated by tools/fontgen/FontGen.java from \"" + ttf + "\".");
            out.println("# Dot Matrix typeface (c) Daniel Hart, SIL Open Font License 1.1 (see OFL.txt).");
            out.println("font " + name);
            out.println("ascent " + ascent);
            out.println("descent " + descent);
            for (int cp = 0x20; cp <= 0x2122; cp++) {
                if (!Character.isDefined(cp) || Character.isISOControl(cp) || !font.canDisplay(cp)) continue;
                String s = new String(Character.toChars(cp));
                GlyphVector gv = font.createGlyphVector(frc, s);
                int advance = Math.round(gv.getGlyphMetrics(0).getAdvance());
                Shape shape = gv.getGlyphOutline(0);
                if (cp != ' ' && !isDotGrid(shape)) continue;
                if (advance <= 0) continue;
                out.printf("glyph %04x %d%n", cp, advance);
                for (int row = -ascent; row < descent; row++) {
                    StringBuilder line = new StringBuilder(advance);
                    for (int col = 0; col < advance; col++) {
                        line.append(shape.contains(col + 0.5, row + 0.5) ? '#' : '.');
                    }
                    out.println(line);
                }
                count++;
            }
        }
        System.out.printf("%s: %d glyphs, ascent %d, descent %d%n", name, count, ascent, descent);
    }

    /** True if the outline is made only of 1x1 squares sitting on the integer grid. */
    private static boolean isDotGrid(Shape shape) {
        List<Rectangle2D> parts = contours(shape);
        if (parts.isEmpty()) return false;
        for (Rectangle2D r : parts) {
            if (Math.abs(r.getWidth() - 1) > 0.02 || Math.abs(r.getHeight() - 1) > 0.02) return false;
            if (Math.abs(r.getX() - Math.round(r.getX())) > 0.02) return false;
            if (Math.abs(r.getY() - Math.round(r.getY())) > 0.02) return false;
        }
        return true;
    }

    private static List<Rectangle2D> contours(Shape shape) {
        List<Rectangle2D> parts = new ArrayList<>();
        Path2D.Double cur = null;
        double[] p = new double[6];
        for (PathIterator it = shape.getPathIterator(null); !it.isDone(); it.next()) {
            switch (it.currentSegment(p)) {
                case PathIterator.SEG_MOVETO -> {
                    if (cur != null) parts.add(cur.getBounds2D());
                    cur = new Path2D.Double();
                    cur.moveTo(p[0], p[1]);
                }
                case PathIterator.SEG_LINETO -> cur.lineTo(p[0], p[1]);
                case PathIterator.SEG_QUADTO -> cur.quadTo(p[0], p[1], p[2], p[3]);
                case PathIterator.SEG_CUBICTO -> cur.curveTo(p[0], p[1], p[2], p[3], p[4], p[5]);
                default -> { }
            }
        }
        if (cur != null) parts.add(cur.getBounds2D());
        return parts;
    }
}
