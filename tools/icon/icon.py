"""Writes Dotboard's adaptive icon layers: an amber dot-matrix "D" on a grid of dim dots."""
import sys

out = sys.argv[1]  # res/ directory

LETTER = [
    "####..",
    "#...#.",
    "#....#",
    "#....#",
    "#....#",
    "#...#.",
    "####..",
]
COLS, ROWS = 6, 7
PITCH = 8.0
R = 3.1
# 108dp canvas, keep everything inside the 66dp safe zone (21..87), grid centred.
X0 = 54 - (COLS - 1) * PITCH / 2
Y0 = 54 - (ROWS - 1) * PITCH / 2


def circle(cx, cy):
    return f"M{cx - R:.2f},{cy:.2f}a{R},{R} 0 1,0 {2 * R:.2f},0a{R},{R} 0 1,0 {-2 * R:.2f},0z"


lit, dim = [], []
for row in range(ROWS):
    for col in range(COLS):
        cx, cy = X0 + col * PITCH, Y0 + row * PITCH
        (lit if LETTER[row][col] == "#" else dim).append(circle(cx, cy))


def vector(paths):
    body = "\n".join(
        f'    <path\n        android:fillColor="{color}"\n        android:pathData="{"".join(d)}" />' for color, d in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by an icon script: dot-matrix \"D\". Original artwork, no third-party branding. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f"{body}\n</vector>\n"
    )


open(f"{out}/drawable/ic_launcher_foreground.xml", "w").write(vector([("#FF2A1D00", dim), ("#FFFFB300", lit)]))
open(f"{out}/drawable/ic_launcher_monochrome.xml", "w").write(vector([("#FFFFFFFF", lit)]))
print(f"{len(lit)} lit, {len(dim)} dim dots")
